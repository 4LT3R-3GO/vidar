DROP TABLE IF EXISTS FLAG;
DROP TABLE IF EXISTS secrets;
DROP TABLE IF EXISTS products;
DROP TABLE IF EXISTS quantity_def;
DROP TABLE IF EXISTS transactions;
DROP TABLE IF EXISTS messages;
DROP TABLE IF EXISTS customers;
DROP TABLE IF EXISTS employee_wine_lottery;
DROP TABLE IF EXISTS vigenere;

-------------------------------------------------------------
-- creating the tables 


-- Create users (4 columns)
CREATE TABLE users (
    id  INTEGER PRIMARY KEY AUTOINCREMENT,
    username TEXT NOT NULL,
    password TEXT, 
    roles INTEGER DEFAULT 0
);

-- create roles (2 columns)
CREATE TABLE roles (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    description TEXT UNIQUE
);

-- create quantity definition table (3 columns)
CREATE TABLE quantity_def ( 
    id INTEGER PRIMARY KEY,
    size_text TEXT NOT NULL,
    definition TEXT NOT NULL
);

-- Products table (7 columns)
CREATE TABLE products (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    name TEXT NOT NULL,
    price REAL NOT NULL,
    weight REAL,              
    quantity_def INTEGER,     
    quantity_size INTEGER,
    storage_quantity INTEGER,
    FOREIGN KEY (quantity_def) REFERENCES quantity_def(id)
);

-- FLAG table (1 column)
CREATE TABLE FLAG (
    flag TEXT NOT NULL
);

-- create secrets (4 columns)

CREATE TABLE secrets (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    owner_id INTEGER,
    secret_text TEXT NOT NULL,
    future_delete_date DATE,
    FOREIGN KEY (owner_id) REFERENCES users(id)
);

-- create table for transactions (7 columns)
CREATE TABLE transactions (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    amount REAL NOT NULL, 
    from_customer_id INTEGER NOT NULL,
    intiated_date DATETIME default CURRENT_TIMESTAMP, 
    completed_date DATETIME,
    method TEXT NOT NULL,
    autorized_by INTEGER,
    FOREIGN KEY (autorized_by) REFERENCES users(id)
);

-- create messages (5 columns)
CREATE TABLE messages (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    sender_id INTEGER,
    receiver_id INTEGER,
    content TEXT,
    opened INTEGER DEFAULT 0,
    FOREIGN KEY (sender_id) REFERENCES users(id),
    FOREIGN KEY (receiver_id) REFERENCES users(id)
);

-- create table for customers (19 columns)
CREATE TABLE customers (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    first_name TEXT NOT NULL,
    last_name TEXT NOT NULL,
    email TEXT UNIQUE,
    phone TEXT UNIQUE,
    prefered_size TEXT,
    fax TEXT UNIQUE,
    address_line1 TEXT NOT NULL,
    address_line2 TEXT,
    city TEXT NOT NULL, 
    postal_code TEXT NOT NULL,
    country TEXT NOT NULL,
    date_of_birth DATE,
    role INT NOT NULL DEFAULT 0,
    create_time DATETIME DEFAULT CURRENT_TIMESTAMP,
    updated_time DATETIME,
    account_balance REAL DEFAULT 0.0,
    loyalty_discount INTEGER DEFAULT 0,
    notes TEXT,
    FOREIGN KEY (role) REFERENCES roles(id)
);


-- create table employee_wine_lottery (12 columns)
CREATE TABLE employee_wine_lottery (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    draw_date DATE DEFAULT CURRENT_DATE,
    prize_name TEXT NOT NULL,
    prize_value REAL,
    bottle_size_ml INTEGER,
    vintage_year INTEGER,
    grape_content TEXT,
    region TEXT,
    winner_employee_id INTEGER, 
    ticket_number TEXT,
    claimed INTEGER DEFAULT 0,
    notes TEXT,
    FOREIGN KEY (winner_employee_id) REFERENCES users(id)
);


-- create vigenere table (26 columns)
CREATE TABLE vigenere (
    row_label CHAR(1) PRIMARY KEY,
    c1 CHAR(1), c2 CHAR(1), c3 CHAR(1), c4 CHAR(1), c5 CHAR(1),
    c6 CHAR(1), c7 CHAR(1), c8 CHAR(1), c9 CHAR(1), c10 CHAR(1),
    c11 CHAR(1), c12 CHAR(1), c13 CHAR(1), c14 CHAR(1), c15 CHAR(1),
